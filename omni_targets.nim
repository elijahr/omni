proc collectTargets(stmt: Stmt, targets: var seq[string]) =
  if stmt == nil: return
  case stmt.kind
  of skAssign:
    targets.add(stmt.target)
  of skIf:
    for s in stmt.thenStmts: collectTargets(s, targets)
    for b in stmt.elifBranches:
      for s in b.stmts: collectTargets(s, targets)
    for s in stmt.elseStmts: collectTargets(s, targets)
  of skWhile:
    for s in stmt.whileStmts: collectTargets(s, targets)
  of skExpr:
    discard

