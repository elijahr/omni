proc emitPd*(m: OmniModule): string =
  var b = ""
  b.add("/* =============================================================================\n")
  b.add(" * Pure Data (Pd) External generated by Omni compiler\n")
  b.add(" * Module: " & m.name & "~\n")
  b.add(" * Target: Pure Data Audio External (.pd_darwin, .pd_linux, .pd_windows)\n")
  b.add(" * ============================================================================= */\n\n")

  # Embed the C core code first
  b.add(emitC(m))
  b.add("\n/* --- Pure Data External Wrapper --- */\n\n")
  b.add("#if defined(__has_include)\n")
  b.add("#  if __has_include(<m_pd.h>)\n")
  b.add("#    include <m_pd.h>\n")
  b.add("#  elif __has_include(\"m_pd.h\")\n")
  b.add("#    include \"m_pd.h\"\n")
  b.add("#  endif\n")
  b.add("#endif\n\n")
  b.add("#ifndef PD_MAJOR_VERSION\n")
  b.add("// Minimal Pure Data C ABI compatibility declarations\n")
  b.add("typedef float t_float;\n")
  b.add("typedef float t_sample;\n")
  b.add("typedef intptr_t t_int;\n")
  b.add("typedef struct _symbol { char *s_name; struct _class **s_thing; struct _symbol *s_next; } t_symbol;\n")
  b.add("typedef struct _class t_class;\n")
  b.add("typedef struct _atom { int a_type; union { t_float w_float; t_symbol *w_symbol; } a_w; } t_atom;\n")
  b.add("typedef struct _object { void *dummy; } t_object;\n")
  b.add("typedef struct _signal { int s_n; t_sample *s_vec; t_float s_sr; int s_refcount; int s_isborrowed; struct _signal *s_next; } t_signal;\n")
  b.add("typedef void *(*t_newmethod)(void *, ...);\n")
  b.add("typedef void (*t_method)(void *, ...);\n")
  b.add("extern t_class *class_new(t_symbol *s, t_newmethod newmeth, t_method freemeth, size_t size, int flags, int arg1, ...);\n")
  b.add("extern void class_addmethod(t_class *c, t_method fn, t_symbol *sel, int arg1, ...);\n")
  b.add("extern void *pd_new(t_class *cls);\n")
  b.add("extern void dsp_add(t_int *(*perform)(t_int *w), int n, ...);\n")
  b.add("extern t_symbol *gensym(const char *s);\n")
  b.add("extern void *signalinlet_new(t_object *x, t_float f);\n")
  b.add("extern void *outlet_new(t_object *x, t_symbol *s);\n")
  b.add("extern float sys_getsr(void);\n")
  b.add("extern t_symbol s_signal;\n")
  b.add("#define CLASS_DEFAULT 0\n")
  b.add("#define A_GIMME 2\n")
  b.add("#define A_CANT 3\n")
  b.add("#define CLASS_MAINSIGNALIN(c, type, field) class_addmethod(c, (t_method)0, gensym(\"signal\"), A_CANT, 0)\n")
  b.add("#endif\n\n")

  let numIns = max(m.inputs.len, 1)
  let numOuts = max(m.outputs.len, 1)

  b.add("static t_class *" & m.name & "_tilde_class = NULL;\n\n")
  b.add("typedef struct _" & m.name & "_tilde {\n")
  b.add("    t_object x_obj;\n")
  b.add("    " & m.name & "* dsp;\n")
  b.add("    t_sample f;\n")
  b.add("    const float* in_ptrs[" & $numIns & "];\n")
  b.add("    float* out_ptrs[" & $numOuts & "];\n")
  b.add("} t_" & m.name & "_tilde;\n\n")

  # Perform method
  b.add("static t_int *" & m.name & "_tilde_perform(t_int *w) {\n")
  b.add("    t_" & m.name & "_tilde *x = (t_" & m.name & "_tilde *)(w[1]);\n")
  b.add("    int n = (int)(w[2]);\n")
  b.add("    int offset = 3;\n")
  for i in 0 ..< m.inputs.len:
    b.add("    x->in_ptrs[" & $i & "] = (const float *)(w[offset++]);\n")
  for i in 0 ..< m.outputs.len:
    b.add("    x->out_ptrs[" & $i & "] = (float *)(w[offset++]);\n")
  b.add("    if (x->dsp) {\n")
  b.add("        " & m.name & "_process(x->dsp, x->in_ptrs, x->out_ptrs, n);\n")
  b.add("    }\n")
  let totalArgs = 2 + m.inputs.len + m.outputs.len
  b.add("    return (w + " & $totalArgs & " + 1);\n")
  b.add("}\n\n")

  # DSP method
  b.add("static void " & m.name & "_tilde_dsp(t_" & m.name & "_tilde *x, t_signal **sp) {\n")
  b.add("    if (x->dsp && sp[0]) {\n")
  b.add("        x->dsp->samplerate = (double)sp[0]->s_sr;\n")
  b.add("    }\n")
  b.add("    dsp_add((t_int *(*)(t_int *))" & m.name & "_tilde_perform, " & $totalArgs & ", x, sp[0]->s_n")
  for i in 0 ..< m.inputs.len:
    b.add(", sp[" & $i & "]->s_vec")
  for i in 0 ..< m.outputs.len:
    let outIdx = m.inputs.len + i
    b.add(", sp[" & $outIdx & "]->s_vec")
  b.add(");\n")
  b.add("}\n\n")

  # New routine
  b.add("static void *" & m.name & "_tilde_new(t_symbol *s, int argc, t_atom *argv) {\n")
  b.add("    (void)s; (void)argc; (void)argv;\n")
  b.add("    t_" & m.name & "_tilde *x = (t_" & m.name & "_tilde *)pd_new(" & m.name & "_tilde_class);\n")
  b.add("    x->f = 0.0f;\n")
  for i in 1 ..< m.inputs.len:
    b.add("    signalinlet_new(&x->x_obj, x->f);\n")
  for i in 0 ..< m.outputs.len:
    b.add("    outlet_new(&x->x_obj, gensym(\"signal\"));\n")
  b.add("    x->dsp = " & m.name & "_alloc();\n")
  b.add("    float sr = sys_getsr();\n")
  b.add("    " & m.name & "_init(x->dsp, sr > 0.0f ? sr : 48000.0);\n")
  b.add("    return (void *)x;\n")
  b.add("}\n\n")

  # Free routine
  b.add("static void " & m.name & "_tilde_free(t_" & m.name & "_tilde *x) {\n")
  b.add("    if (x && x->dsp) {\n")
  b.add("        " & m.name & "_free(x->dsp);\n")
  b.add("        x->dsp = NULL;\n")
  b.add("    }\n")
  b.add("}\n\n")

  # Setup routine
  b.add("void " & m.name & "_tilde_setup(void) {\n")
  b.add("    " & m.name & "_tilde_class = class_new(gensym(\"" & m.name & "~\"),\n")
  b.add("        (t_newmethod)" & m.name & "_tilde_new,\n")
  b.add("        (t_method)" & m.name & "_tilde_free,\n")
  b.add("        sizeof(t_" & m.name & "_tilde),\n")
  b.add("        CLASS_DEFAULT,\n")
  b.add("        A_GIMME, 0);\n")
  b.add("    CLASS_MAINSIGNALIN(" & m.name & "_tilde_class, t_" & m.name & "_tilde, f);\n")
  b.add("    class_addmethod(" & m.name & "_tilde_class, (t_method)" & m.name & "_tilde_dsp, gensym(\"dsp\"), A_CANT, 0);\n")
  b.add("}\n")

  return b

