proc emitMax*(m: OmniModule): string =
  var b = ""
  b.add("/* =============================================================================\n")
  b.add(" * Max/MSP Audio External generated by Omni compiler\n")
  b.add(" * Module: " & m.name & "~\n")
  b.add(" * ============================================================================= */\n\n")
  b.add(emitC(m))
  b.add("\n#include \"ext.h\"\n")
  b.add("#include \"ext_obex.h\"\n")
  b.add("#include \"z_dsp.h\"\n\n")
  b.add("typedef struct _" & m.name & "_max {\n")
  b.add("    t_pxobject ob;\n")
  b.add("    " & m.name & "* dsp;\n")
  b.add("    const float* in_ptrs[" & $max(m.inputs.len, 1) & "];\n")
  b.add("    float* out_ptrs[" & $max(m.outputs.len, 1) & "];\n")
  b.add("} t_" & m.name & "_max;\n\n")
  b.add("static void *" & m.name & "_max_class;\n\n")
  b.add("void " & m.name & "_max_perform64(t_" & m.name & "_max *x, t_object *dsp64, double **ins, long numins, double **outs, long numouts, long sampleframes, long flags, void *userparam) {\n")
  b.add("    (void)dsp64; (void)flags; (void)userparam;\n")
  b.add("    // Convert or process audio blocks\n")
  b.add("    if (!x->dsp) return;\n")
  b.add("    // Buffer conversion from double to float if needed\n")
  b.add("}\n\n")
  b.add("void " & m.name & "_max_dsp64(t_" & m.name & "_max *x, t_object *dsp64, short *count, double samplerate, long maxvectorsize, long flags) {\n")
  b.add("    (void)count; (void)maxvectorsize; (void)flags;\n")
  b.add("    if (x->dsp) x->dsp->samplerate = samplerate;\n")
  b.add("    object_method(dsp64, gensym(\"dsp_add64\"), x, " & m.name & "_max_perform64, 0, NULL);\n")
  b.add("}\n\n")
  b.add("void *" & m.name & "_max_new(t_symbol *s, long argc, t_atom *argv) {\n")
  b.add("    (void)s; (void)argc; (void)argv;\n")
  b.add("    t_" & m.name & "_max *x = (t_" & m.name & "_max *)object_alloc(" & m.name & "_max_class);\n")
  b.add("    dsp_setup((t_pxobject *)x, " & $m.inputs.len & ");\n")
  for i in 0 ..< m.outputs.len:
    b.add("    outlet_new(x, \"signal\");\n")
  b.add("    x->dsp = " & m.name & "_alloc();\n")
  b.add("    " & m.name & "_init(x->dsp, sys_getsr());\n")
  b.add("    return x;\n")
  b.add("}\n\n")
  b.add("void " & m.name & "_max_free(t_" & m.name & "_max *x) {\n")
  b.add("    dsp_free((t_pxobject *)x);\n")
  b.add("    if (x->dsp) {\n")
  b.add("        " & m.name & "_free(x->dsp);\n")
  b.add("        x->dsp = NULL;\n")
  b.add("    }\n")
  b.add("}\n\n")
  b.add("void ext_main(void *r) {\n")
  b.add("    t_class *c = class_new(\"" & m.name & "~\", (method)" & m.name & "_max_new, (method)" & m.name & "_max_free, sizeof(t_" & m.name & "_max), 0L, A_GIMME, 0);\n")
  b.add("    class_addmethod(c, (method)" & m.name & "_max_dsp64, \"dsp64\", A_CANT, 0);\n")
  b.add("    class_dspinit(c);\n")
  b.add("    class_register(CLASS_BOX, c);\n")
  b.add("    " & m.name & "_max_class = c;\n")
  b.add("}\n")
  return b
