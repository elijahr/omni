proc emitNimExpr(expr: Expr): string =
  if expr == nil: return "0.0"
  case expr.kind
  of ekNum:
    if expr.isInt: return $expr.intVal
    return $expr.numVal
  of ekSym:
    return expr.symName
  of ekUnary:
    if expr.uop == "not":
      return "(not " & emitNimExpr(expr.uexpr) & ")"
    return "(" & expr.uop & emitNimExpr(expr.uexpr) & ")"
  of ekBinary:
    if expr.bop == "%":
      return "omni_mod(" & emitNimExpr(expr.lhs) & ", " & emitNimExpr(expr.rhs) & ")"
    return "(" & emitNimExpr(expr.lhs) & " " & expr.bop & " " & emitNimExpr(expr.rhs) & ")"
  of ekCall:
    var s = expr.callee & "("
    for i, a in expr.args:
      if i > 0: s.add(", ")
      s.add(emitNimExpr(a))
    s.add(")")
    return s
  of ekIf:
    let condStr = emitNimExpr(expr.ifCond)
    let thenStr = emitNimExpr(expr.ifThen)
    let elseStr = if expr.ifElse != nil: emitNimExpr(expr.ifElse) else: "0.0"
    return "(if " & condStr & ": " & thenStr & " else: " & elseStr & ")"

proc emitNimStmt(stmt: Stmt, indent: string): string =
  if stmt == nil: return ""
  var b = ""
  case stmt.kind
  of skAssign:
    b.add(indent & stmt.target & " " & stmt.assignOp & " " & emitNimExpr(stmt.val) & "\n")
  of skIf:
    b.add(indent & "if " & emitNimExpr(stmt.cond) & ":\n")
    if stmt.thenStmts.len == 0:
      b.add(indent & "  discard\n")
    else:
      for s in stmt.thenStmts: b.add(emitNimStmt(s, indent & "  "))
    for branch in stmt.elifBranches:
      b.add(indent & "elif " & emitNimExpr(branch.cond) & ":\n")
      if branch.stmts.len == 0:
        b.add(indent & "  discard\n")
      else:
        for s in branch.stmts: b.add(emitNimStmt(s, indent & "  "))
    if stmt.elseStmts.len > 0:
      b.add(indent & "else:\n")
      for s in stmt.elseStmts: b.add(emitNimStmt(s, indent & "  "))
  of skWhile:
    b.add(indent & "while " & emitNimExpr(stmt.whileCond) & ":\n")
    if stmt.whileStmts.len == 0:
      b.add(indent & "  discard\n")
    else:
      for s in stmt.whileStmts: b.add(emitNimStmt(s, indent & "  "))
  of skExpr:
    b.add(indent & "discard " & emitNimExpr(stmt.callExpr) & "\n")
  return b

proc emitNim*(m: OmniModule): string =
  var b = ""
  b.add("# =============================================================================\n")
  b.add("# Pure Nim Module generated by Omni compiler\n")
  b.add("# Module: " & m.name & "\n")
  b.add("# Target: Pure Nim (Standalone Audio Processing)\n")
  b.add("# =============================================================================\n\n")
  b.add("import math\n\n")
  b.add("const TWOPI* = 6.28318530717958647692\n")
  b.add("const PI* = 3.14159265358979323846\n\n")
  b.add("template omni_mod*(a, b: untyped): untyped =\n")
  b.add("  math.floorMod(float(a), float(b))\n\n")
  b.add("proc omni_sat24*(x: float32): float32 {.inline.} =\n")
  b.add("  if x > 0.99999988'f32: 0.99999988'f32\n")
  b.add("  elif x < -1.0'f32: -1.0'f32\n")
  b.add("  else: x\n\n")

  # Type definition
  b.add("type\n")
  b.add("  " & m.name & "* = object\n")
  b.add("    samplerate*: float64\n")
  for p in m.params:
    b.add("    " & p.name & "*: float32\n")
  for sv in m.stateVars:
    b.add("    " & sv.name & "*: float32\n")
  b.add("\n")

  # Init proc
  b.add("proc init*(m: var " & m.name & ", samplerate: float64 = 48000.0) =\n")
  b.add("  m.samplerate = samplerate\n")
  for p in m.params:
    b.add("  m." & p.name & " = " & $p.defaultVal & "'f32\n")
  for sv in m.stateVars:
    b.add("  m." & sv.name & " = " & $sv.initVal & "'f32\n")
  b.add("\n")

  # New constructor
  b.add("proc new" & m.name & "*(samplerate: float64 = 48000.0): ref " & m.name & " =\n")
  b.add("  new(result)\n")
  b.add("  result[].init(samplerate)\n\n")

  # Process buffer proc
  b.add("proc process*(m: var " & m.name & ",\n")
  b.add("              ins: openArray[seq[float32]],\n")
  b.add("              outs: var openArray[seq[float32]],\n")
  b.add("              numSamples: int) =\n")
  b.add("  let samplerate {.used.} = if m.samplerate > 0.0: m.samplerate else: 48000.0\n")
  for p in m.params:
    b.add("  var " & p.name & " {.used.} = m." & p.name & "\n")
  for sv in m.stateVars:
    b.add("  var " & sv.name & " {.used.} = m." & sv.name & "\n")

  var declaredLocals = initTable[string, bool]()
  for i in m.inputs: declaredLocals[i] = true
  for o in m.outputs: declaredLocals[o] = true
  for p in m.params: declaredLocals[p.name] = true
  for sv in m.stateVars: declaredLocals[sv.name] = true

  var allTargets: seq[string] = @[]
  for s in m.performStmts: collectTargets(s, allTargets)
  for s in m.sampleStmts: collectTargets(s, allTargets)

  var uniqueLocals: seq[string] = @[]
  for t in allTargets:
    if t notin declaredLocals and t notin uniqueLocals:
      uniqueLocals.add(t)
      declaredLocals[t] = true

  for t in uniqueLocals:
    b.add("  var " & t & " {.used.}: float32 = 0.0'f32\n")

  for s in m.performStmts:
    b.add(emitNimStmt(s, "  "))

  b.add("\n  for i in 0 ..< numSamples:\n")
  for idx, inName in m.inputs:
    b.add("    let " & inName & " {.used.} = if ins.len > " & $idx & " and ins[" & $idx & "].len > i: ins[" & $idx & "][i] else: 0.0'f32\n")
  for outName in m.outputs:
    b.add("    var " & outName & " {.used.}: float32 = 0.0'f32\n")

  for s in m.sampleStmts:
    b.add(emitNimStmt(s, "    "))

  for idx, outName in m.outputs:
    b.add("    if outs.len > " & $idx & " and outs[" & $idx & "].len > i:\n")
    b.add("      outs[" & $idx & "][i] = " & outName & "\n")

  b.add("\n  # Save state variables back\n")
  for sv in m.stateVars:
    b.add("  m." & sv.name & " = " & sv.name & "\n")

  return b

