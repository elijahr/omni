proc emitSuperColliderClass*(m: OmniModule): string =
  var b = ""
  b.add("// =============================================================================\n")
  b.add("// SuperCollider Class Definition for Omni Module: " & m.name & "\n")
  b.add("// =============================================================================\n\n")
  b.add(m.name & " : UGen {\n")
  
  # Method *ar
  var args: seq[string] = @[]
  for inName in m.inputs:
    args.add(inName & ": 0.0")
  for p in m.params:
    args.add(p.name & ": " & $p.defaultVal)
  
  b.add("    *ar { | " & args.join(", ") & " |\n")
  var callArgs: seq[string] = @["'audio'"]
  for inName in m.inputs: callArgs.add(inName)
  for p in m.params: callArgs.add(p.name)
  b.add("        ^this.multiNew(" & callArgs.join(", ") & ")\n")
  b.add("    }\n\n")

  # Number of outputs
  b.add("    checkInputs {\n")
  b.add("        ^this.checkNInputs(" & $m.inputs.len & ")\n")
  b.add("    }\n\n")
  b.add("    init { | ...theInputs |\n")
  b.add("        inputs = theInputs;\n")
  b.add("        ^this.initOutputs(" & $max(m.outputs.len, 1) & ", rate);\n")
  b.add("    }\n")
  b.add("}\n")
  return b

proc emitSuperColliderCpp*(m: OmniModule): string =
  var b = ""
  b.add("/* =============================================================================\n")
  b.add(" * SuperCollider UGen Plugin generated by Omni compiler\n")
  b.add(" * Module: " & m.name & "\n")
  b.add(" * ============================================================================= */\n\n")
  b.add(emitC(m))
  b.add("\n#include \"SC_PlugIn.h\"\n\n")
  b.add("static InterfaceTable *ft;\n\n")
  b.add("struct " & m.name & "_SC : public Unit {\n")
  b.add("    " & m.name & "* dsp;\n")
  b.add("    const float* in_ptrs[" & $max(m.inputs.len, 1) & "];\n")
  b.add("    float* out_ptrs[" & $max(m.outputs.len, 1) & "];\n")
  b.add("};\n\n")
  b.add("static void " & m.name & "_next(" & m.name & "_SC *unit, int inNumSamples) {\n")
  for i in 0 ..< m.inputs.len:
    b.add("    unit->in_ptrs[" & $i & "] = IN(" & $i & ");\n")
  for i in 0 ..< m.outputs.len:
    b.add("    unit->out_ptrs[" & $i & "] = OUT(" & $i & ");\n")
  b.add("    if (unit->dsp) {\n")
  b.add("        " & m.name & "_process(unit->dsp, unit->in_ptrs, unit->out_ptrs, inNumSamples);\n")
  b.add("    }\n")
  b.add("}\n\n")
  b.add("static void " & m.name & "_Ctor(" & m.name & "_SC *unit) {\n")
  b.add("    unit->dsp = " & m.name & "_alloc();\n")
  b.add("    " & m.name & "_init(unit->dsp, SAMPLERATE);\n")
  b.add("    SETCALC(" & m.name & "_next);\n")
  b.add("    " & m.name & "_next(unit, 1);\n")
  b.add("}\n\n")
  b.add("static void " & m.name & "_Dtor(" & m.name & "_SC *unit) {\n")
  b.add("    if (unit->dsp) {\n")
  b.add("        " & m.name & "_free(unit->dsp);\n")
  b.add("        unit->dsp = nullptr;\n")
  b.add("    }\n")
  b.add("}\n\n")
  b.add("PluginLoad(" & m.name & "UGens) {\n")
  b.add("    ft = inTable;\n")
  b.add("    DefineDtorUnit(" & m.name & "_SC);\n")
  b.add("}\n")
  return b

